#!/usr/bin/env python3
"""Generate the sample game's sprites, atlas, sound effects and music (Python stdlib only).

Usage:
    python3 tools/gen_assets.py [--out DIR]          # write Brick Breaker's assets
    python3 tools/gen_assets.py --check [--out DIR]  # validate existing assets
    python3 tools/gen_assets.py --template-out DIR   # write the new-game template's starter assets
    python3 tools/gen_assets.py --ios-icon-out DIR --icon-style template|brickbreaker
                                                     # write an AppIcon.appiconset (1024 px, opaque)
"""

import argparse
import math
import os
import random
import struct
import sys
import wave
import zlib

DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "games", "brickbreaker", "assets")
ATLAS_SIZE = 256
PADDING = 2

# ---------------------------------------------------------------------------- images


def write_png(path, width, height, rgba, channels=4):
    """rgba: bytearray of width*height*channels (4 = RGBA, 3 = RGB without alpha)."""
    raw = bytearray()
    stride = width * channels
    for y in range(height):
        raw.append(0)  # filter: none
        raw += rgba[y * stride:(y + 1) * stride]

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    color_type = 6 if channels == 4 else 2
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def coverage(dist):
    """Signed distance (negative inside) -> anti-aliased alpha in [0,1]."""
    return max(0.0, min(1.0, 0.5 - dist))


def rounded_rect_sdf(px, py, w, h, r):
    qx = abs(px - w / 2) - (w / 2 - r)
    qy = abs(py - h / 2) - (h / 2 - r)
    outside = math.hypot(max(qx, 0), max(qy, 0))
    return outside + min(max(qx, qy), 0) - r


def make_sprite(w, h, shader):
    pixels = bytearray(w * h * 4)
    for y in range(h):
        for x in range(w):
            lum, alpha = shader(x + 0.5, y + 0.5)
            i = (y * w + x) * 4
            v = int(max(0, min(255, round(lum * 255))))
            pixels[i:i + 4] = bytes((v, v, v, int(round(alpha * 255))))
    return pixels


def paddle_shader(w, h):
    def shade(x, y):
        a = coverage(rounded_rect_sdf(x, y, w, h, h / 2))
        lum = 0.82 + 0.18 * (1 - y / h)  # lighter top edge
        return lum, a
    return shade


def brick_shader(w, h):
    def shade(x, y):
        a = coverage(rounded_rect_sdf(x, y, w, h, 6))
        inner = rounded_rect_sdf(x, y, w, h, 6) < -3
        lum = (0.92 - 0.25 * (y / h)) if inner else 1.0
        return lum, a
    return shade


def ball_shader(d):
    def shade(x, y):
        r = d / 2
        dist = math.hypot(x - r, y - r) - (r - 0.5)
        hl = math.hypot(x - r * 0.7, y - r * 0.7) / r
        return 0.85 + 0.15 * max(0.0, 1 - hl), coverage(dist)
    return shade


def particle_shader(d):
    def shade(x, y):
        r = d / 2
        t = min(1.0, math.hypot(x - r, y - r) / r)
        return 1.0, (1 - t) ** 2
    return shade


SPRITES = [  # name, w, h, shader factory
    ("paddle", 160, 32, lambda: paddle_shader(160, 32)),
    ("brick", 80, 36, lambda: brick_shader(80, 36)),
    ("ball", 32, 32, lambda: ball_shader(32)),
    ("particle", 16, 16, lambda: particle_shader(16)),
    ("pixel", 4, 4, lambda: (lambda x, y: (1.0, 1.0))),
]


def build_atlas(out):
    atlas = bytearray(ATLAS_SIZE * ATLAS_SIZE * 4)
    regions = []
    x = y = PADDING
    shelf_h = 0
    for name, w, h, factory in SPRITES:
        if x + w + PADDING > ATLAS_SIZE:
            x, y = PADDING, y + shelf_h + PADDING
            shelf_h = 0
        if y + h + PADDING > ATLAS_SIZE:
            sys.exit(f"atlas overflow placing {name}")
        pixels = make_sprite(w, h, factory())
        for row in range(h):
            dst = ((y + row) * ATLAS_SIZE + x) * 4
            atlas[dst:dst + w * 4] = pixels[row * w * 4:(row + 1) * w * 4]
        regions.append((name, x, y, w, h))
        x += w + PADDING
        shelf_h = max(shelf_h, h)

    write_png(os.path.join(out, "sprites.png"), ATLAS_SIZE, ATLAS_SIZE, atlas)
    with open(os.path.join(out, "sprites.atlas"), "w") as f:
        f.write("# Generated by tools/gen_assets.py: name x y w h\n")
        f.write("image sprites.png\n")
        for r in regions:
            f.write("%s %d %d %d %d\n" % r)
    return regions

# ---------------------------------------------------------------------------- audio


def write_wav(path, rate, samples):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        frames = bytearray()
        for s in samples:
            frames += struct.pack("<h", int(max(-1.0, min(1.0, s)) * 32000))
        w.writeframes(bytes(frames))


def envelope(t, length, attack=0.004):
    if t < attack:
        return t / attack
    return max(0.0, 1 - (t - attack) / (length - attack)) ** 2


def sfx_hit(rate=44100):
    n = int(rate * 0.08)
    return [0.6 * envelope(i / rate, 0.08) * (1 if math.sin(2 * math.pi * 880 * i / rate) > 0 else -1) * 0.5
            for i in range(n)]


def sfx_break(rate=44100):
    rng = random.Random(1234)
    n = int(rate * 0.18)
    out, phase = [], 0.0
    for i in range(n):
        t = i / rate
        freq = 600 - 400 * (t / 0.18)
        phase += 2 * math.pi * freq / rate
        out.append(envelope(t, 0.18) * (0.45 * math.sin(phase) + 0.35 * rng.uniform(-1, 1)))
    return out


def sfx_lose(rate=44100):
    n = int(rate * 0.4)
    out, phase = [], 0.0
    for i in range(n):
        t = i / rate
        freq = 440 * (0.25 ** (t / 0.4))
        phase += 2 * math.pi * freq / rate
        out.append(0.4 * envelope(t, 0.4, 0.01) * (1 if math.sin(phase) > 0 else -1))
    return out


def music_loop(rate=22050):
    """16 s, 120 bpm, 8 bars: Am F C G (2 bars each), 16th-note triangle arpeggio + sine bass."""
    def midi(n):
        return 440.0 * 2 ** ((n - 69) / 12)

    chords = [(57, 60, 64), (53, 57, 60), (48, 52, 55), (55, 59, 62)]  # Am F C G
    sixteenth = 0.125
    total = int(rate * 16.0)
    out = [0.0] * total

    def add_note(start, length, freq, amp, wave_fn):
        s0 = int(start * rate)
        for i in range(int(length * rate)):
            if s0 + i >= total:
                break
            t = i / rate
            out[s0 + i] += amp * envelope(t, length, 0.005) * wave_fn(2 * math.pi * freq * t)

    triangle = lambda ph: 2 / math.pi * math.asin(math.sin(ph))
    pattern = [0, 1, 2, 1, 2, 0, 1, 2]
    for step in range(128):  # 8 bars * 16 sixteenths
        chord = chords[(step // 32) % 4]
        note = chord[pattern[step % 8]] + 12
        add_note(step * sixteenth, sixteenth * 0.95, midi(note), 0.22, triangle)
    for beat in range(32):  # bass on quarter notes
        chord = chords[(beat // 8) % 4]
        add_note(beat * 0.5, 0.45, midi(chord[0] - 12), 0.30, math.sin)
    return out

# ---------------------------------------------------------------------------- template


def logo_shader(d):
    """Rounded square with an inner ring: a neutral placeholder logo, tinted at runtime."""
    def shade(x, y):
        outer = rounded_rect_sdf(x, y, d, d, d * 0.22)
        r = math.hypot(x - d / 2, y - d / 2)
        ring = abs(r - d * 0.28) - d * 0.05
        base = 1.0 - 0.2 * (y / d)
        lum = base + (0.55 - base) * coverage(ring)  # anti-aliased ring
        return lum, coverage(outer)
    return shade


def sfx_tap(rate=44100):
    n = int(rate * 0.06)
    return [0.5 * envelope(i / rate, 0.06, 0.002) * math.sin(2 * math.pi * 1320 * i / rate) for i in range(n)]


def build_template_assets(out):
    size = 128
    atlas = bytearray(size * size * 4)
    regions = []
    for name, x, y, w, h, shader in [("logo", PADDING, PADDING, 96, 96, logo_shader(96)),
                                     ("pixel", 96 + 2 * PADDING, PADDING, 4, 4, lambda x, y: (1.0, 1.0))]:
        pixels = make_sprite(w, h, shader)
        for row in range(h):
            dst = ((y + row) * size + x) * 4
            atlas[dst:dst + w * 4] = pixels[row * w * 4:(row + 1) * w * 4]
        regions.append((name, x, y, w, h))
    os.makedirs(os.path.join(out, "sfx"), exist_ok=True)
    write_png(os.path.join(out, "sprites.png"), size, size, atlas)
    with open(os.path.join(out, "sprites.atlas"), "w") as f:
        f.write("# Generated by tools/gen_assets.py --template-out: name x y w h\n")
        f.write("image sprites.png\n")
        for r in regions:
            f.write("%s %d %d %d %d\n" % r)
    write_wav(os.path.join(out, "sfx", "tap.wav"), 44100, sfx_tap())
    print("wrote template assets to", out)

# ---------------------------------------------------------------------------- iOS app icon

ICON_SIZE = 1024
BG = (0x14, 0x1A, 0x2E)


def mix(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))


def icon_template(x, y):
    """Dark background with the template's cyan logo (rounded square + ring)."""
    d = ICON_SIZE * 0.62
    ox = oy = (ICON_SIZE - d) / 2
    lx, ly = x - ox, y - oy
    col = BG
    inside = coverage(rounded_rect_sdf(lx, ly, d, d, d * 0.22))
    if inside > 0:
        cyan = mix((0x4C, 0xC9, 0xF0), (0x2E, 0x8F, 0xB5), ly / d)
        ring = coverage(abs(math.hypot(lx - d / 2, ly - d / 2) - d * 0.28) - d * 0.05)
        logo = mix(cyan, (0x1F, 0x5E, 0x78), ring)
        col = mix(col, logo, inside)
    return col


def icon_brickbreaker(x, y):
    """Dark background, three brick rows, a ball and a paddle."""
    col = BG
    colors = [(0xFF, 0xD1, 0x66), (0xF7, 0x25, 0x85), (0x4C, 0xC9, 0xF0)]
    bw, bh, gap, top = 200, 90, 28, 200
    left = (ICON_SIZE - (4 * bw + 3 * gap)) / 2
    for row in range(3):
        for c in range(4):
            bx, by = left + c * (bw + gap), top + row * (bh + gap)
            cov = coverage(rounded_rect_sdf(x - bx, y - by, bw, bh, 18))
            if cov > 0:
                col = mix(col, colors[row], cov)
    ball = coverage(math.hypot(x - 600, y - 640) - 52)
    col = mix(col, (0xF0, 0xF2, 0xFA), ball)
    paddle = coverage(rounded_rect_sdf(x - 312, y - 800, 400, 76, 38))
    return mix(col, (0xE8, 0xEA, 0xF6), paddle)


def build_ios_icon(out_dir, style):
    shader = icon_template if style == "template" else icon_brickbreaker
    pixels = bytearray(ICON_SIZE * ICON_SIZE * 3)
    for y in range(ICON_SIZE):
        for x in range(ICON_SIZE):
            i = (y * ICON_SIZE + x) * 3
            pixels[i:i + 3] = bytes(shader(x + 0.5, y + 0.5))
    os.makedirs(out_dir, exist_ok=True)
    # RGB, no alpha channel: App Store Connect rejects icons that have one.
    write_png(os.path.join(out_dir, "AppIcon-1024.png"), ICON_SIZE, ICON_SIZE, pixels, channels=3)
    with open(os.path.join(out_dir, "Contents.json"), "w") as f:
        f.write('{\n  "images" : [\n    {\n      "filename" : "AppIcon-1024.png",\n      "idiom" : "universal",\n'
                '      "platform" : "ios",\n      "size" : "1024x1024"\n    }\n  ],\n'
                '  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  }\n}\n')
    catalog = os.path.dirname(os.path.normpath(out_dir))
    with open(os.path.join(catalog, "Contents.json"), "w") as f:
        f.write('{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  }\n}\n')
    print("wrote", style, "app icon to", out_dir)

# ---------------------------------------------------------------------------- check


def check(out):
    required = ["sprites.png", "sprites.atlas", "sfx/hit.wav", "sfx/break.wav", "sfx/lose.wav",
                "music/loop.wav", "fonts/Fredoka.ttf", "fonts/OFL.txt"]
    ok = True
    for rel in required:
        path = os.path.join(out, rel)
        if not os.path.isfile(path) or os.path.getsize(path) == 0:
            print("MISSING", rel)
            ok = False
    if not ok:
        return False
    with open(os.path.join(out, "sprites.png"), "rb") as f:
        if f.read(8) != b"\x89PNG\r\n\x1a\n":
            print("BAD PNG")
            return False
    with open(os.path.join(out, "sprites.atlas")) as f:
        lines = [l.split() for l in f if l.strip() and not l.startswith("#")]
    if lines[0] != ["image", "sprites.png"]:
        print("BAD atlas header")
        return False
    for name, *nums in lines[1:]:
        x, y, w, h = map(int, nums)
        if x < 0 or y < 0 or x + w > ATLAS_SIZE or y + h > ATLAS_SIZE:
            print("BAD region", name)
            return False
    for rel in required[2:6]:
        with wave.open(os.path.join(out, rel)) as w:
            if w.getnframes() == 0:
                print("EMPTY", rel)
                return False
    for rel in required:
        print("ok", rel)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--template-out", metavar="DIR")
    ap.add_argument("--ios-icon-out", metavar="DIR", help=".../Assets.xcassets/AppIcon.appiconset")
    ap.add_argument("--icon-style", choices=["template", "brickbreaker"], default="template")
    args = ap.parse_args()
    if args.ios_icon_out:
        build_ios_icon(os.path.normpath(args.ios_icon_out), args.icon_style)
        return
    if args.template_out:
        build_template_assets(os.path.normpath(args.template_out))
        return
    out = os.path.normpath(args.out)

    if args.check:
        sys.exit(0 if check(out) else 1)

    os.makedirs(os.path.join(out, "sfx"), exist_ok=True)
    os.makedirs(os.path.join(out, "music"), exist_ok=True)
    regions = build_atlas(out)
    write_wav(os.path.join(out, "sfx", "hit.wav"), 44100, sfx_hit())
    write_wav(os.path.join(out, "sfx", "break.wav"), 44100, sfx_break())
    write_wav(os.path.join(out, "sfx", "lose.wav"), 44100, sfx_lose())
    write_wav(os.path.join(out, "music", "loop.wav"), 22050, music_loop())
    print("atlas regions:", ", ".join(r[0] for r in regions))
    print("wrote assets to", out)


if __name__ == "__main__":
    main()
