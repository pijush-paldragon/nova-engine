#!/usr/bin/env python3
"""Generate the sample game's sprites, atlas, sound effects and music (Python stdlib only).

Usage:
    python3 tools/gen_assets.py [--out DIR]      # write assets
    python3 tools/gen_assets.py --check [--out DIR]  # validate existing assets
"""

import argparse
import math
import os
import random
import struct
import sys
import wave
import zlib

DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "games", "brickbreaker", "assets")
ATLAS_SIZE = 256
PADDING = 2

# ---------------------------------------------------------------------------- images


def write_png(path, width, height, rgba):
    """rgba: bytearray of width*height*4."""
    raw = bytearray()
    stride = width * 4
    for y in range(height):
        raw.append(0)  # filter: none
        raw += rgba[y * stride:(y + 1) * stride]

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def coverage(dist):
    """Signed distance (negative inside) -> anti-aliased alpha in [0,1]."""
    return max(0.0, min(1.0, 0.5 - dist))


def rounded_rect_sdf(px, py, w, h, r):
    qx = abs(px - w / 2) - (w / 2 - r)
    qy = abs(py - h / 2) - (h / 2 - r)
    outside = math.hypot(max(qx, 0), max(qy, 0))
    return outside + min(max(qx, qy), 0) - r


def make_sprite(w, h, shader):
    pixels = bytearray(w * h * 4)
    for y in range(h):
        for x in range(w):
            lum, alpha = shader(x + 0.5, y + 0.5)
            i = (y * w + x) * 4
            v = int(max(0, min(255, round(lum * 255))))
            pixels[i:i + 4] = bytes((v, v, v, int(round(alpha * 255))))
    return pixels


def paddle_shader(w, h):
    def shade(x, y):
        a = coverage(rounded_rect_sdf(x, y, w, h, h / 2))
        lum = 0.82 + 0.18 * (1 - y / h)  # lighter top edge
        return lum, a
    return shade


def brick_shader(w, h):
    def shade(x, y):
        a = coverage(rounded_rect_sdf(x, y, w, h, 6))
        inner = rounded_rect_sdf(x, y, w, h, 6) < -3
        lum = (0.92 - 0.25 * (y / h)) if inner else 1.0
        return lum, a
    return shade


def ball_shader(d):
    def shade(x, y):
        r = d / 2
        dist = math.hypot(x - r, y - r) - (r - 0.5)
        hl = math.hypot(x - r * 0.7, y - r * 0.7) / r
        return 0.85 + 0.15 * max(0.0, 1 - hl), coverage(dist)
    return shade


def particle_shader(d):
    def shade(x, y):
        r = d / 2
        t = min(1.0, math.hypot(x - r, y - r) / r)
        return 1.0, (1 - t) ** 2
    return shade


SPRITES = [  # name, w, h, shader factory
    ("paddle", 160, 32, lambda: paddle_shader(160, 32)),
    ("brick", 80, 36, lambda: brick_shader(80, 36)),
    ("ball", 32, 32, lambda: ball_shader(32)),
    ("particle", 16, 16, lambda: particle_shader(16)),
    ("pixel", 4, 4, lambda: (lambda x, y: (1.0, 1.0))),
]


def build_atlas(out):
    atlas = bytearray(ATLAS_SIZE * ATLAS_SIZE * 4)
    regions = []
    x = y = PADDING
    shelf_h = 0
    for name, w, h, factory in SPRITES:
        if x + w + PADDING > ATLAS_SIZE:
            x, y = PADDING, y + shelf_h + PADDING
            shelf_h = 0
        if y + h + PADDING > ATLAS_SIZE:
            sys.exit(f"atlas overflow placing {name}")
        pixels = make_sprite(w, h, factory())
        for row in range(h):
            dst = ((y + row) * ATLAS_SIZE + x) * 4
            atlas[dst:dst + w * 4] = pixels[row * w * 4:(row + 1) * w * 4]
        regions.append((name, x, y, w, h))
        x += w + PADDING
        shelf_h = max(shelf_h, h)

    write_png(os.path.join(out, "sprites.png"), ATLAS_SIZE, ATLAS_SIZE, atlas)
    with open(os.path.join(out, "sprites.atlas"), "w") as f:
        f.write("# Generated by tools/gen_assets.py: name x y w h\n")
        f.write("image sprites.png\n")
        for r in regions:
            f.write("%s %d %d %d %d\n" % r)
    return regions

# ---------------------------------------------------------------------------- audio


def write_wav(path, rate, samples):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        frames = bytearray()
        for s in samples:
            frames += struct.pack("<h", int(max(-1.0, min(1.0, s)) * 32000))
        w.writeframes(bytes(frames))


def envelope(t, length, attack=0.004):
    if t < attack:
        return t / attack
    return max(0.0, 1 - (t - attack) / (length - attack)) ** 2


def sfx_hit(rate=44100):
    n = int(rate * 0.08)
    return [0.6 * envelope(i / rate, 0.08) * (1 if math.sin(2 * math.pi * 880 * i / rate) > 0 else -1) * 0.5
            for i in range(n)]


def sfx_break(rate=44100):
    rng = random.Random(1234)
    n = int(rate * 0.18)
    out, phase = [], 0.0
    for i in range(n):
        t = i / rate
        freq = 600 - 400 * (t / 0.18)
        phase += 2 * math.pi * freq / rate
        out.append(envelope(t, 0.18) * (0.45 * math.sin(phase) + 0.35 * rng.uniform(-1, 1)))
    return out


def sfx_lose(rate=44100):
    n = int(rate * 0.4)
    out, phase = [], 0.0
    for i in range(n):
        t = i / rate
        freq = 440 * (0.25 ** (t / 0.4))
        phase += 2 * math.pi * freq / rate
        out.append(0.4 * envelope(t, 0.4, 0.01) * (1 if math.sin(phase) > 0 else -1))
    return out


def music_loop(rate=22050):
    """16 s, 120 bpm, 8 bars: Am F C G (2 bars each), 16th-note triangle arpeggio + sine bass."""
    def midi(n):
        return 440.0 * 2 ** ((n - 69) / 12)

    chords = [(57, 60, 64), (53, 57, 60), (48, 52, 55), (55, 59, 62)]  # Am F C G
    sixteenth = 0.125
    total = int(rate * 16.0)
    out = [0.0] * total

    def add_note(start, length, freq, amp, wave_fn):
        s0 = int(start * rate)
        for i in range(int(length * rate)):
            if s0 + i >= total:
                break
            t = i / rate
            out[s0 + i] += amp * envelope(t, length, 0.005) * wave_fn(2 * math.pi * freq * t)

    triangle = lambda ph: 2 / math.pi * math.asin(math.sin(ph))
    pattern = [0, 1, 2, 1, 2, 0, 1, 2]
    for step in range(128):  # 8 bars * 16 sixteenths
        chord = chords[(step // 32) % 4]
        note = chord[pattern[step % 8]] + 12
        add_note(step * sixteenth, sixteenth * 0.95, midi(note), 0.22, triangle)
    for beat in range(32):  # bass on quarter notes
        chord = chords[(beat // 8) % 4]
        add_note(beat * 0.5, 0.45, midi(chord[0] - 12), 0.30, math.sin)
    return out

# ---------------------------------------------------------------------------- check


def check(out):
    required = ["sprites.png", "sprites.atlas", "sfx/hit.wav", "sfx/break.wav", "sfx/lose.wav",
                "music/loop.wav", "fonts/Fredoka.ttf", "fonts/OFL.txt"]
    ok = True
    for rel in required:
        path = os.path.join(out, rel)
        if not os.path.isfile(path) or os.path.getsize(path) == 0:
            print("MISSING", rel)
            ok = False
    if not ok:
        return False
    with open(os.path.join(out, "sprites.png"), "rb") as f:
        if f.read(8) != b"\x89PNG\r\n\x1a\n":
            print("BAD PNG")
            return False
    with open(os.path.join(out, "sprites.atlas")) as f:
        lines = [l.split() for l in f if l.strip() and not l.startswith("#")]
    if lines[0] != ["image", "sprites.png"]:
        print("BAD atlas header")
        return False
    for name, *nums in lines[1:]:
        x, y, w, h = map(int, nums)
        if x < 0 or y < 0 or x + w > ATLAS_SIZE or y + h > ATLAS_SIZE:
            print("BAD region", name)
            return False
    for rel in required[2:6]:
        with wave.open(os.path.join(out, rel)) as w:
            if w.getnframes() == 0:
                print("EMPTY", rel)
                return False
    for rel in required:
        print("ok", rel)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = os.path.normpath(args.out)

    if args.check:
        sys.exit(0 if check(out) else 1)

    os.makedirs(os.path.join(out, "sfx"), exist_ok=True)
    os.makedirs(os.path.join(out, "music"), exist_ok=True)
    regions = build_atlas(out)
    write_wav(os.path.join(out, "sfx", "hit.wav"), 44100, sfx_hit())
    write_wav(os.path.join(out, "sfx", "break.wav"), 44100, sfx_break())
    write_wav(os.path.join(out, "sfx", "lose.wav"), 44100, sfx_lose())
    write_wav(os.path.join(out, "music", "loop.wav"), 22050, music_loop())
    print("atlas regions:", ", ".join(r[0] for r in regions))
    print("wrote assets to", out)


if __name__ == "__main__":
    main()
