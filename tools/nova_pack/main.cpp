// nova_pack — build and inspect Nova asset packs (game.pak).
//
//   nova_pack keygen <file>                                  new random key (64 hex chars)
//   nova_pack embed-key <keyfile> <out.cpp>                  C++ source defining nova::detail::packKey()
//   nova_pack pack <assets-dir> <out.pak> [--key-file <f>]   pack every file under the folder
//   nova_pack verify <in.pak> [--key-file <f>]               decrypt + check every entry
//   nova_pack list <in.pak> [--key-file <f>]                 path, size, stored size, raw|zstd
//
// The key comes from $NOVA_PACK_KEY when set, else from the key file.
#include "pack_format.hpp"

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <optional>
#include <sstream>
#include <string>
#include <vector>

#if defined(__APPLE__)
#include <stdlib.h> // arc4random_buf
#else
#include <sys/random.h>
#endif
#include <unistd.h>

namespace fs = std::filesystem;
using namespace nova::pack;

namespace {

int fail(const std::string& message) {
    std::fprintf(stderr, "error: %s\n", message.c_str());
    return 1;
}

void randomBytes(uint8_t* out, size_t n) {
#if defined(__APPLE__)
    arc4random_buf(out, n);
#else
    while (n > 0) {
        ssize_t got = getrandom(out, n, 0);
        if (got > 0) {
            out += got;
            n -= size_t(got);
        }
    }
#endif
}

std::optional<std::vector<uint8_t>> readAll(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) return std::nullopt;
    return std::vector<uint8_t>(std::istreambuf_iterator<char>(in), {});
}

// $NOVA_PACK_KEY first, then the key file.
std::optional<Key> loadKey(const std::optional<fs::path>& keyFile, std::string& error) {
    Key key;
    if (const char* env = std::getenv("NOVA_PACK_KEY"); env && *env) {
        if (parseKeyHex(env, key)) return key;
        error = "NOVA_PACK_KEY must be 64 hex characters";
        return std::nullopt;
    }
    if (!keyFile) {
        error = "no key: pass --key-file <file> or set NOVA_PACK_KEY";
        return std::nullopt;
    }
    auto text = readAll(*keyFile);
    if (!text) {
        error = "can't read key file " + keyFile->string();
        return std::nullopt;
    }
    if (!parseKeyHex(std::string_view(reinterpret_cast<const char*>(text->data()), text->size()), key)) {
        error = "key file " + keyFile->string() + " must contain 64 hex characters";
        return std::nullopt;
    }
    return key;
}

int keygen(const fs::path& file) {
    if (fs::exists(file)) return fail(file.string() + " already exists (refusing to overwrite a key)");
    if (file.has_parent_path()) fs::create_directories(file.parent_path());
    Key key;
    randomBytes(key.data(), key.size());
    std::ofstream out(file, std::ios::binary);
    out << keyToHex(key) << '\n';
    wipe(key.data(), key.size());
    return out ? 0 : fail("can't write " + file.string());
}

int embedKey(const fs::path& keyFile, const fs::path& outCpp) {
    std::string error;
    auto key = loadKey(keyFile, error);
    if (!key) return fail(error);
    // key = s0 ^ s1 ^ s2 ^ s3, with fresh random s0..s2 every time, so the key never appears whole.
    std::array<Key, 4> shares;
    for (int i = 0; i < 3; ++i) randomBytes(shares[size_t(i)].data(), kKeySize);
    for (size_t b = 0; b < kKeySize; ++b) shares[3][b] = (*key)[b] ^ shares[0][b] ^ shares[1][b] ^ shares[2][b];
    std::ostringstream src;
    src << "// Generated by nova_pack embed-key at build time. Do not commit.\n"
           "#include <cstdint>\n\nnamespace {\n";
    for (int i = 0; i < 4; ++i) {
        src << "volatile const std::uint8_t kShare" << i << "[32] = {";
        for (size_t b = 0; b < kKeySize; ++b) src << (b ? "," : "") << unsigned(shares[size_t(i)][b]);
        src << "};\n";
    }
    src << "} // namespace\n\nnamespace nova::detail {\n"
           "void packKey(std::uint8_t out[32]) {\n"
           "    for (int i = 0; i < 32; ++i) out[i] = std::uint8_t(kShare0[i] ^ kShare1[i] ^ kShare2[i] ^ kShare3[i]);\n"
           "}\n} // namespace nova::detail\n";
    for (Key& s : shares) wipe(s.data(), s.size());
    wipe(key->data(), key->size());
    if (outCpp.has_parent_path()) fs::create_directories(outCpp.parent_path());
    std::ofstream out(outCpp, std::ios::binary);
    out << src.str();
    return out ? 0 : fail("can't write " + outCpp.string());
}

int pack(const fs::path& assets, const fs::path& outPak, const std::optional<fs::path>& keyFile) {
    std::string error;
    auto key = loadKey(keyFile, error);
    if (!key) return fail(error);
    if (!fs::is_directory(assets)) return fail(assets.string() + " is not a folder");

    std::vector<std::pair<std::string, fs::path>> files;
    for (const auto& item : fs::recursive_directory_iterator(assets)) {
        if (!item.is_regular_file()) continue;
        fs::path rel = fs::relative(item.path(), assets);
        bool hidden = std::any_of(rel.begin(), rel.end(), [](const fs::path& p) { return p.string().rfind('.', 0) == 0; });
        if (!hidden) files.emplace_back(rel.generic_u8string(), item.path());
    }
    std::sort(files.begin(), files.end());

    std::vector<Entry> entries;
    std::vector<uint8_t> data;
    std::vector<uint8_t> packed;
    for (const auto& [rel, path] : files) {
        auto original = readAll(path);
        if (!original) return fail("can't read " + path.string());
        if (original->size() > UINT32_MAX) return fail(rel + " is larger than 4 GiB");
        Entry e;
        e.path = rel;
        e.originalSize = uint32_t(original->size());
        const std::vector<uint8_t>* stored = &*original;
        if (compress(original->data(), original->size(), packed)) {
            e.compression = kZstd;
            stored = &packed;
        }
        e.nonce = entryNonce(*key, rel, e.compression, stored->data(), stored->size());
        e.dataOff = kHeaderSize + data.size();
        e.storedSize = uint32_t(stored->size());
        size_t at = data.size();
        data.resize(at + stored->size() + kTagSize);
        seal(*key, e.nonce, reinterpret_cast<const uint8_t*>(rel.data()), rel.size(), stored->data(),
             stored->size(), data.data() + at, data.data() + at + stored->size());
        entries.push_back(std::move(e));
    }

    std::vector<uint8_t> index = encodeIndex(entries);
    Header header;
    header.indexOff = kHeaderSize + data.size();
    header.indexSize = index.size();
    header.indexNonce = deriveNonce(*key, "nova-index", nullptr, 0, index.data(), index.size());
    auto headerBytes = encodeHeader(header);
    std::vector<uint8_t> indexCipher(index.size() + kTagSize);
    seal(*key, header.indexNonce, headerBytes.data(), headerBytes.size(), index.data(), index.size(),
         indexCipher.data(), indexCipher.data() + index.size());
    wipe(key->data(), key->size());

    // Write to a private temp file and rename, so concurrent builds never see a half-written pack.
    if (outPak.has_parent_path()) fs::create_directories(outPak.parent_path());
    fs::path tmp = outPak;
    tmp += ".tmp." + std::to_string(getpid());
    {
        std::ofstream out(tmp, std::ios::binary);
        out.write(reinterpret_cast<const char*>(headerBytes.data()), std::streamsize(headerBytes.size()));
        out.write(reinterpret_cast<const char*>(data.data()), std::streamsize(data.size()));
        out.write(reinterpret_cast<const char*>(indexCipher.data()), std::streamsize(indexCipher.size()));
        if (!out) {
            out.close();
            fs::remove(tmp);
            return fail("can't write " + outPak.string());
        }
    }
    std::error_code ec;
    fs::rename(tmp, outPak, ec);
    if (ec) {
        fs::remove(tmp);
        return fail("can't write " + outPak.string() + ": " + ec.message());
    }
    return 0;
}

// Opens and decrypts a pack's index; optionally decrypts every entry.
int inspect(const fs::path& pakPath, const std::optional<fs::path>& keyFile, bool listOnly) {
    std::string error;
    auto key = loadKey(keyFile, error);
    if (!key) return fail(error);
    auto pak = readAll(pakPath);
    if (!pak) return fail("can't read " + pakPath.string());
    Header header;
    if (pak->size() < kHeaderSize || !decodeHeader(pak->data(), header)) return fail("not a Nova pack (bad header)");
    if (!indexInRange(header, pak->size())) return fail("damaged pack (index out of range)");
    std::vector<uint8_t> index(header.indexSize);
    const uint8_t* cipher = pak->data() + header.indexOff;
    if (!open(*key, header.indexNonce, pak->data(), kHeaderSize, cipher, header.indexSize, cipher + header.indexSize,
              index.data()))
        return fail("index authentication failed (wrong key or modified pack)");
    std::vector<Entry> entries;
    if (!decodeIndex(index.data(), index.size(), entries)) return fail("damaged pack (bad index)");
    std::vector<uint8_t> plain, original;
    for (const Entry& e : entries) {
        if (listOnly) {
            std::printf("%s\t%u\t%u\t%s\n", e.path.c_str(), e.originalSize, e.storedSize,
                        e.compression == kZstd ? "zstd" : "raw");
            continue;
        }
        if (e.dataOff < kHeaderSize || e.dataOff > header.indexOff || e.storedSize + kTagSize > header.indexOff - e.dataOff)
            return fail(e.path + ": out of range");
        plain.resize(e.storedSize);
        const uint8_t* c = pak->data() + e.dataOff;
        if (!open(*key, e.nonce, reinterpret_cast<const uint8_t*>(e.path.data()), e.path.size(), c, e.storedSize,
                  c + e.storedSize, plain.data()))
            return fail(e.path + ": authentication failed");
        if (e.compression == kZstd && !decompress(plain.data(), plain.size(), e.originalSize, original))
            return fail(e.path + ": decompression failed");
    }
    wipe(key->data(), key->size());
    if (!listOnly) std::printf("ok: %zu entries\n", entries.size());
    return 0;
}

int usage() {
    std::fprintf(stderr,
                 "usage:\n  nova_pack keygen <file>\n  nova_pack embed-key <keyfile> <out.cpp>\n"
                 "  nova_pack pack <assets-dir> <out.pak> [--key-file <f>]\n"
                 "  nova_pack verify <in.pak> [--key-file <f>]\n  nova_pack list <in.pak> [--key-file <f>]\n"
                 "The key comes from $NOVA_PACK_KEY when set, else from --key-file.\n");
    return 1;
}

} // namespace

int main(int argc, char** argv) {
    std::vector<std::string> args(argv + 1, argv + argc);
    std::optional<fs::path> keyFile;
    for (size_t i = 0; i + 1 < args.size(); ++i) {
        if (args[i] == "--key-file") {
            keyFile = args[i + 1];
            args.erase(args.begin() + long(i), args.begin() + long(i) + 2);
            break;
        }
    }
    if (args.empty()) return usage();
    const std::string& cmd = args[0];
    try {
        if (cmd == "keygen" && args.size() == 2) return keygen(args[1]);
        if (cmd == "embed-key" && args.size() == 3) return embedKey(args[1], args[2]);
        if (cmd == "pack" && args.size() == 3) return pack(args[1], args[2], keyFile);
        if (cmd == "verify" && args.size() == 2) return inspect(args[1], keyFile, false);
        if (cmd == "list" && args.size() == 2) return inspect(args[1], keyFile, true);
    } catch (const std::exception& e) {
        return fail(e.what());
    }
    return usage();
}
